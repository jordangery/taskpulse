/**
 * 回傳 [start, end) 範圍內所有台灣假日的 Map（YYYY-MM-DD → 名稱）
 * 範圍以「日」為單位、local time。end 是 exclusive。
 */
export function getTaiwanHolidaysInRange(start: Date, end: Date): Map<string, string> {
  const map = new Map<string, string>()
  const s = startOfDay(start)
  const e = startOfDay(end)
  // 逐日掃，最多 ~28 天，O(n) 無壓力
  let cursor = s
  while (cursor < e) {
    const key = toLocalKey(cursor)
    const name = HOLIDAYS[key]
    if (name) map.set(key, name)
    cursor = addDays(cursor, 1)
  }
  return map
}
